/**
 * Theme definitions.
 *
 * Each palette declares a COMPLETE token set for both light and dark mode, so
 * every mode × palette combination resolves on its own. Nothing inherits from a
 * base theme — that guarantees no combination can render one theme's text on
 * another theme's background.
 *
 * Values are space-separated RGB channels (not hex) so Tailwind's
 * `<alpha-value>` modifiers work: `bg-accent/10`, `border-line/60`, etc.
 */

export type Mode = "light" | "dark";

export type PaletteId =
  | "slate"
  | "graphite"
  | "ink"
  | "linen"
  | "forest"
  | "plum"
  | "nord"
  | "rose"
  | "nord-classic"
  | "catppuccin"
  | "dracula"
  | "gruvbox"
  | "tokyo-night"
  | "solarized";

/** The tokens every theme must define. */
export interface ThemeTokens {
  ground: string;
  surface: string;
  "surface-alt": string;
  /** Raised row background — the Windows 11 settings card. */
  "surface-raised": string;
  border: string;
  "border-soft": string;
  text: string;
  "text-muted": string;
  "text-faint": string;
  accent: string;
  "accent-hover": string;
  "accent-text": string;
  "st-modified": string;
  "st-added": string;
  "st-deleted": string;
  /** Two stops for the ambient background wash behind the app. */
  "glow-a": string;
  "glow-b": string;
}

export interface Palette {
  id: PaletteId;
  name: string;
  /** Shown under the name in the settings row. */
  description: string;
  /** Themes beyond the first four live behind "More options". */
  extended: boolean;
  light: ThemeTokens;
  dark: ThemeTokens;
}

